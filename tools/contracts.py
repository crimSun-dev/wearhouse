"""Wearhouse v2 contract generation and drift check (offline: no database, identity or weather calls).

    python tools/contracts.py generate   # export openapi-v2.json, then src/schema.d.ts and src/error-codes.d.ts
    python tools/contracts.py check      # regenerate in memory/temp and fail on any difference

Requires apps/api installed (apps/api/.venv or the active interpreter) and `npm ci` in packages/contracts.
Legacy v1 types are separate (legacy/web: npm run types:api from legacy/contracts/openapi-v1.json).
"""
from __future__ import annotations

import ast
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTRACTS = ROOT / "packages" / "contracts"
SPEC = CONTRACTS / "openapi-v2.json"
TYPES = CONTRACTS / "src" / "schema.d.ts"
CODES = CONTRACTS / "src" / "error-codes.d.ts"
API_SRC = ROOT / "apps" / "api" / "src" / "wearhouse"
REGEN = "python tools/contracts.py generate"
NL = "\n"
CRLF = "\r\n"


def _python() -> str:
    venv = ROOT / "apps" / "api" / ".venv" / ("Scripts/python.exe" if os.name == "nt" else "bin/python")
    return str(venv) if venv.exists() else sys.executable


def _read(path: Path) -> str:
    return path.read_text(encoding="utf-8").replace(CRLF, NL) if path.exists() else ""


def export_spec() -> str:
    """Build the app with offline settings and print its OpenAPI document (no engine is created)."""
    code = ("from wearhouse.bootstrap.cli import export_openapi; import sys; "
            "sys.stdout.buffer.write(export_openapi().encode('utf-8'))")
    env = {k: v for k, v in os.environ.items() if not k.startswith("WEARHOUSE_")}  # no live config leaks in
    out = subprocess.run([_python(), "-c", code], capture_output=True, check=True, env=env)
    return out.stdout.decode("utf-8").replace(CRLF, NL)


def _gen_types(spec_path: Path, out: Path) -> str:
    cli = CONTRACTS / "node_modules" / "openapi-typescript" / "bin" / "cli.js"
    if not cli.exists():
        sys.exit("packages/contracts/node_modules missing: run `npm ci --prefix packages/contracts` first")
    subprocess.run(["node", str(cli), str(spec_path), "-o", str(out)], check=True, capture_output=True)
    return _read(out)


def error_codes() -> list[str]:
    """Every stable error `code` the v2 API can emit, found by parsing its source (AST, deterministic)."""
    pat = re.compile(r"^[A-Z][A-Z_]{3,}$")
    found: set[str] = set()
    for path in sorted(API_SRC.rglob("*.py")):
        for node in ast.walk(ast.parse(path.read_text(encoding="utf-8"))):
            if isinstance(node, ast.Call):
                fn = node.func.id if isinstance(node.func, ast.Name) else getattr(node.func, "attr", "")
                if fn in ("ApiError", "conflict", "error_body"):
                    found |= {a.value for a in node.args
                              if isinstance(a, ast.Constant) and isinstance(a.value, str) and pat.match(a.value)}
            elif isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id.endswith("_CODE")
                                                      for t in node.targets):
                if isinstance(node.value, ast.Constant) and isinstance(node.value.value, str):
                    found.add(node.value.value)
            elif isinstance(node, ast.Tuple) and len(node.elts) == 2:  # ("NOT_FOUND", "Resource not found.")
                code, msg = node.elts
                if (isinstance(code, ast.Constant) and isinstance(code.value, str) and pat.match(code.value)
                        and isinstance(msg, ast.Constant) and isinstance(msg.value, str) and " " in msg.value):
                    found.add(code.value)
    return sorted(found)


def codes_dts() -> str:
    lines = ["// Generated by tools/contracts.py from the v2 API source. Do not edit.",
             "// Every stable `code` an error response ({code, message, request_id, field_errors?}) can carry.",
             "export type ErrorCode ="]
    lines += [f"  | '{c}'" for c in error_codes()]
    return NL.join(lines) + ";" + NL


def generate() -> None:
    SPEC.write_text(export_spec(), encoding="utf-8", newline=NL)
    TYPES.write_text(_gen_types(SPEC, TYPES), encoding="utf-8", newline=NL)
    CODES.write_text(codes_dts(), encoding="utf-8", newline=NL)
    print(f"wrote {SPEC.relative_to(ROOT)}, {TYPES.relative_to(ROOT)} and {CODES.relative_to(ROOT)}")


def check() -> int:
    problems = []
    fresh_spec = export_spec()
    if export_spec() != fresh_spec:
        problems.append("OpenAPI export is not deterministic")
    if _read(SPEC) != fresh_spec:
        problems.append(f"{SPEC.relative_to(ROOT)} is stale versus the API declarations")
    with tempfile.TemporaryDirectory() as tmp:
        spec = Path(tmp) / "openapi-v2.json"
        spec.write_text(fresh_spec, encoding="utf-8", newline=NL)
        a = _gen_types(spec, Path(tmp) / "a.d.ts")
        b = _gen_types(spec, Path(tmp) / "b.d.ts")
    if a != b:
        problems.append("TypeScript generation is not deterministic")
    if _read(TYPES) != a:
        problems.append(f"{TYPES.relative_to(ROOT)} is stale versus the OpenAPI document")
    if _read(CODES) != codes_dts():
        problems.append(f"{CODES.relative_to(ROOT)} is stale versus the API's error codes")
    if problems:
        print("CONTRACT DRIFT:" + NL + "  - " + (NL + "  - ").join(problems) + NL + f"Regenerate with: {REGEN}",
              file=sys.stderr)
        return 1
    print("contracts up to date (two clean generations match the checked-in files)")
    return 0


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "check"
    if cmd == "generate":
        generate()
    elif cmd == "check":
        sys.exit(check())
    else:
        sys.exit(__doc__)
