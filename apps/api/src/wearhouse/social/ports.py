from __future__ import annotations

import uuid
from dataclasses import dataclass
from datetime import datetime
from typing import Protocol

from ..accounts.ports import AccountsRepository
from ..platform.pagination import Position
from ..platform.ports import UnitOfWork
from ..wardrobe.ports import WardrobeRepository


@dataclass(frozen=True)
class ShareRow:
    id: uuid.UUID
    owner_id: uuid.UUID
    look_id: uuid.UUID
    revision_id: uuid.UUID
    audience: str
    caption: str | None
    created_at: datetime
    revoked_at: datetime | None
    moderation_state: str = "visible"  # complete-wearhouse-tdd: hidden shares are invisible to everyone but the owner


class SocialRepository(Protocol):
    # moderation + inspiration (complete-wearhouse-tdd)
    def add_report(self, report_id: uuid.UUID, share_id: uuid.UUID, reporter_id: uuid.UUID, reason: str,
                   now: datetime) -> bool: ...
    def open_reports(self, limit: int) -> list[dict]: ...
    def resolve_reports(self, share_id: uuid.UUID, status: str, now: datetime) -> None: ...
    def set_moderation(self, share_id: uuid.UUID, state: str, actor: uuid.UUID, reason: str, now: datetime) -> None: ...
    def reports_by(self, user_id: uuid.UUID) -> list[dict]: ...
    def add_inspiration(self, inspiration_id: uuid.UUID, user_id: uuid.UUID, share_id: uuid.UUID, snapshot: dict,
                        now: datetime) -> None: ...
    def inspirations(self, user_id: uuid.UUID) -> list[dict]: ...
    def delete_inspiration(self, user_id: uuid.UUID, inspiration_id: uuid.UUID) -> bool: ...
    def insert_share(self, row: ShareRow) -> None: ...
    def share(self, share_id: uuid.UUID, lock: bool = False) -> ShareRow | None: ...
    def update_share(self, share_id: uuid.UUID, values: dict) -> None: ...
    def shares_of(self, owner_id: uuid.UUID, *, active_only: bool, limit: int) -> list[ShareRow]: ...
    def count_active(self, owner_id: uuid.UUID) -> int: ...
    def shares_by_owners(self, owner_ids: list[uuid.UUID], after: Position | None, limit: int,
                         since: datetime | None = None) -> list[ShareRow]: ...
    def plan_setting(self, user_id: uuid.UUID) -> str: ...
    def set_plan_setting(self, user_id: uuid.UUID, audience: str, now: datetime) -> None: ...
    def read_through(self, user_id: uuid.UUID) -> datetime | None: ...
    def set_read_through(self, user_id: uuid.UUID, at: datetime) -> None: ...
    def showcase(self, user_id: uuid.UUID) -> dict | None: ...
    def put_showcase(self, user_id: uuid.UUID, headline: str | None, accent: str, featured: list[str],
                     now: datetime) -> None: ...
    def erase_all(self, user_id: uuid.UUID) -> None: ...


class SocialUoW(UnitOfWork, Protocol):
    social: SocialRepository
    accounts: AccountsRepository
    wardrobe: WardrobeRepository
