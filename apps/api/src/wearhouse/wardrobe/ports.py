from __future__ import annotations

import uuid
from dataclasses import dataclass
from datetime import date, datetime
from typing import Protocol

from ..accounts.ports import AccountsRepository
from ..catalogue.ports import RevisionReader, SizeRepository
from ..ownership.ports import OwnedItemReader
from ..platform.ports import UnitOfWork


@dataclass(frozen=True)
class DeclaredRow:
    id: uuid.UUID
    name: str
    slot: str
    category: str | None
    colour: str | None
    photo_type: str | None
    photo_sha256: str | None
    archived_at: datetime | None
    created_at: datetime


@dataclass(frozen=True)
class LookRow:
    id: uuid.UUID
    name: str
    current_revision_no: int
    deleted_at: datetime | None
    created_at: datetime


@dataclass(frozen=True)
class LookRevisionRow:
    id: uuid.UUID
    look_id: uuid.UUID
    revision_no: int
    name: str
    slots: dict  # slot -> [item_id str]
    created_at: datetime


@dataclass(frozen=True)
class PlanRow:
    plan_date: date
    look_revision_id: uuid.UUID
    occasion: str | None
    note: str | None


@dataclass(frozen=True)
class WearRow:
    id: uuid.UUID
    worn_on: date
    look_revision_id: uuid.UUID | None
    item_ids: tuple[uuid.UUID, ...]
    created_at: datetime


class WardrobeRepository(Protocol):
    # declared items
    def insert_declared(self, user_id: uuid.UUID, row: DeclaredRow) -> None: ...
    def declared(self, user_id: uuid.UUID) -> list[DeclaredRow]: ...
    def update_declared(self, user_id: uuid.UUID, item_id: uuid.UUID, values: dict) -> bool: ...
    def set_photo(self, user_id: uuid.UUID, item_id: uuid.UUID, data: bytes, ctype: str, sha256: str) -> bool: ...
    def get_photo(self, user_id: uuid.UUID, item_id: uuid.UUID) -> tuple[bytes, str] | None: ...
    # item state
    def states(self, user_id: uuid.UUID) -> dict[uuid.UUID, tuple[str, str | None]]: ...
    def set_state(self, user_id: uuid.UUID, item_id: uuid.UUID, care_state: str, slot_override: str | None,
                  now: datetime) -> None: ...
    # the owner's size correction for any item (add-wearhouse-sizes D6)
    def sizes(self, user_id: uuid.UUID) -> dict[uuid.UUID, tuple[str, str]]: ...
    # owner attribute corrections (align-wearhouse-outfit-recommender)
    def attrs(self, user_id: uuid.UUID) -> dict[uuid.UUID, dict]: ...
    def set_attrs(self, user_id: uuid.UUID, item_id: uuid.UUID, attrs: dict, now: datetime) -> None: ...
    def set_size(self, user_id: uuid.UUID, item_id: uuid.UUID, system: str | None, code: str | None,
                 now: datetime) -> None: ...
    # shelves
    def shelves(self, user_id: uuid.UUID) -> list[dict]: ...
    def shelf(self, user_id: uuid.UUID, shelf_id: uuid.UUID) -> dict | None: ...
    def create_shelf(self, user_id: uuid.UUID, shelf_id: uuid.UUID, name: str, now: datetime) -> bool: ...
    def rename_shelf(self, user_id: uuid.UUID, shelf_id: uuid.UUID, name: str) -> bool: ...
    def replace_shelf_items(self, shelf_id: uuid.UUID, item_ids: list[uuid.UUID]) -> None: ...
    def delete_shelf(self, user_id: uuid.UUID, shelf_id: uuid.UUID) -> bool: ...
    # looks
    def looks(self, user_id: uuid.UUID) -> list[LookRow]: ...
    def look(self, user_id: uuid.UUID, look_id: uuid.UUID, lock: bool = False) -> LookRow | None: ...
    def insert_look(self, user_id: uuid.UUID, look_id: uuid.UUID, name: str, now: datetime) -> None: ...
    def insert_revision(self, row: LookRevisionRow) -> None: ...
    def update_look(self, look_id: uuid.UUID, *, name: str, revision_no: int) -> None: ...
    def soft_delete_look(self, look_id: uuid.UUID, now: datetime) -> None: ...
    def revision(self, user_id: uuid.UUID, revision_id: uuid.UUID) -> LookRevisionRow | None: ...
    def revision_by_no(self, look_id: uuid.UUID, revision_no: int) -> LookRevisionRow | None: ...
    def revisions_of(self, look_id: uuid.UUID) -> list[LookRevisionRow]: ...
    # plans
    def plans(self, user_id: uuid.UUID, start: date, end: date) -> list[PlanRow]: ...
    def set_plan(self, user_id: uuid.UUID, row: PlanRow, now: datetime) -> None: ...
    def clear_plan(self, user_id: uuid.UUID, plan_date: date) -> bool: ...
    # wear
    def insert_wear(self, user_id: uuid.UUID, row: WearRow) -> None: ...
    def wear(self, user_id: uuid.UUID, start: date, end: date) -> list[WearRow]: ...
    def delete_wear(self, user_id: uuid.UUID, wear_id: uuid.UUID) -> bool: ...
    def wear_stats(self, user_id: uuid.UUID) -> dict[uuid.UUID, tuple[int, date]]: ...
    # account
    def erase_all(self, user_id: uuid.UUID) -> None: ...


class RecommendationEvents(Protocol):
    def create_run(self, *, run_id: uuid.UUID, user_id: uuid.UUID, context: dict, suggestions: list, now: datetime) -> None: ...
    def run(self, user_id: uuid.UUID, run_id: uuid.UUID) -> dict | None: ...
    def record_displayed(self, user_id: uuid.UUID, run_id: uuid.UUID, item_ids: list[uuid.UUID], now: datetime) -> None: ...
    def choice(self, run_id: uuid.UUID) -> dict | None: ...
    def record_choice(self, user_id: uuid.UUID, run_id: uuid.UUID, index: int, item_ids: list[uuid.UUID],
                      now: datetime) -> bool: ...
    def counts(self, user_id: uuid.UUID) -> dict[uuid.UUID, tuple[int, int]]: ...
    def export(self, user_id: uuid.UUID) -> dict: ...
    def erase(self, user_id: uuid.UUID) -> None: ...


class WardrobeUoW(UnitOfWork, Protocol):
    wardrobe: WardrobeRepository
    owned: OwnedItemReader
    revisions: RevisionReader
    sizes: SizeRepository
    accounts: AccountsRepository  # settings (add-wearhouse-settings-security)
    reco_events: "RecommendationEvents"  # outfit runs + feedback (align-wearhouse-outfit-recommender)
