"""Phase 5 — measurement harness (Ch 15). Short timeouts keep these runs quick;
the real run uses the 3 s BMKG deadline."""
import json

import pytest

import measure

FAST = dict(runs=5, cold_runs=3, bmkg_timeout_s=0.3, naive_cap_s=0.6)


def test_measure_is_deterministic_given_seed(tmp_path):
    a = measure.run_measurement(seed=7, db_dir=tmp_path / "a", **FAST)
    b = measure.run_measurement(seed=7, db_dir=tmp_path / "b", **FAST)
    assert measure.deterministic_view(a) == measure.deterministic_view(b)
    c = measure.run_measurement(seed=8, db_dir=tmp_path / "c", **FAST)
    assert measure.deterministic_view(c)["metrics"]["M1"] != measure.deterministic_view(a)["metrics"]["M1"]


def test_measure_writes_results_json_with_all_five_metrics(tmp_path):
    out_dir, report = tmp_path / "results", tmp_path / "docs" / "RESULTS.md"
    code = measure.main(["--seed", "3", "--runs", "5", "--cold-runs", "3", "--bmkg-timeout", "0.3",
                         "--naive-cap", "0.6", "--out-dir", str(out_dir), "--report", str(report),
                         "--db-dir", str(tmp_path / "db")])
    assert code == 0
    files = list(out_dir.glob("*.json"))
    assert len(files) == 1
    data = json.loads(files[0].read_text(encoding="utf-8"))
    assert set(data["metrics"]) == {"M1", "M2", "M3", "M4", "M5"}
    for m in data["metrics"].values():
        assert {"name", "baseline", "integrated", "pass_condition", "passed"} <= set(m)
    m = data["metrics"]
    assert m["M1"]["integrated"]["pct_passing"] == 100.0
    assert m["M2"]["integrated"]["max_manual_inputs"] == 0 and m["M2"]["baseline"]["manual_inputs"] == 2
    assert m["M4"]["integrated"]["bad_rejected"] == m["M4"]["integrated"]["bad_total"] == 24
    assert m["M5"]["integrated"]["resilient"] == 4 and m["M5"]["baseline"]["resilient"] == 0
    assert data["meta"]["mode"] == "offline-mock"
    text = report.read_text(encoding="utf-8")
    assert "M1" in text and "M5" in text and "generated by measure.py" in text


def test_measure_refuses_to_run_if_db_cold_without_warmup(tmp_path):
    with pytest.raises(measure.ColdDatabaseError):
        measure.run_measurement(seed=1, db_dir=tmp_path, warmup=False, **FAST)


def test_measure_refuses_to_run_with_a_fault_switched_on(tmp_path, monkeypatch):
    monkeypatch.setattr(measure, "INITIAL_FAULT_FOR_TESTS", "timeout")
    with pytest.raises(measure.MeasurementError, match="fault"):
        measure.run_measurement(seed=1, db_dir=tmp_path, **FAST)


def test_bad_entry_corpus_has_24_entries_and_all_are_rejected():
    corpus = measure.bad_entries()
    assert len(corpus) == 24
    assert measure.m4_validation(measure.synthetic_feed(1, measure.utcnow()))["integrated"]["bad_rejected"] == 24
